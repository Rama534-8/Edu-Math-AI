/**
 * One-shot generator for src/lib/curriculum/cbse-seed.ts
 *
 * The CBSE Class IX 2026-27 syllabus tables are large, so they live in this
 * generator instead of the seed file itself. Running `node build-cbse.mjs`
 * rewrites cbse-seed.ts from the CBSE_CHAPTERS array below.
 *
 * Content is transcribed from scratch/pdf_output.txt (official syllabus):
 *   Unit I   Number System .......... 07 marks (12 periods)
 *   Unit II  Algebra ............... 20 marks (66 periods)
 *   Unit III Coordinate Geometry ... 04 marks ( 6 periods)
 *   Unit IV  Geometry .............. 25 marks (69 periods)
 *   Unit V   Mensuration ........... 14 marks (27 periods)
 *   Unit VI  Statistics and Probability 10 marks (24 periods)
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'src/lib/curriculum/cbse-seed.ts');

const HEADER = `import { t, type ChapterSeed } from './builders';

// ==============================================================================
// CBSE CLASS IX MATHEMATICS - 2026-27 OFFICIAL SYLLABUS
// Source: scratch/pdf_output.txt ("COURSE STRUCTURE CLASS - IX")
//   6 Units, 15 chapters, 80 marks. Each chapter reproduces the official
//   "Key Concepts" (topics) and the published "The student will be able to:"
//   learning outcomes.
//
// GENERATED by build-cbse.mjs - edit that file, then re-run it.
// Chapter + topic IDs deliberately match the previous curriculum-data.ts so
// existing progress rows, assessment snapshots and routes keep resolving.
// ==============================================================================

export const CBSE_SEED: ChapterSeed[] = [
`;

const FOOTER = `];
`;

function renderTopic(topic) {
  const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const arr = (items) =>
    items.length
      ? `[\n${items.map((i) => `          ${q(i)},`).join('\n')}\n        ]`
      : '[]';

  const parts = [
    `      t(`,
    `        ${q(topic.id)},`,
    `        ${q(topic.sectionRef || '')},`,
    `        ${q(topic.title)},`,
    `        ${q(topic.titleTelugu)},`,
    `        ${q(topic.description)},`,
    `        ${q(topic.descriptionTelugu)},`,
    `        ${arr(topic.concepts || [])},`,
    `        ${arr(topic.conceptsTelugu || [])},`,
    `        ${arr(topic.learningObjectives || [])},`,
    `        ${arr(topic.learningObjectivesTelugu || [])}`,
  ];

  const extra = {};
  if (topic.formulas) extra.formulas = topic.formulas;
  if (topic.workedExample) extra.workedExample = topic.workedExample;
  if (topic.estimatedHours) extra.estimatedHours = topic.estimatedHours;

  if (Object.keys(extra).length) {
    // The positional args end without a trailing comma, so add one before the
    // optional `extra` object literal.
    parts.push(`        ,{`);
    for (const [k, v] of Object.entries(extra)) {
      parts.push(`          ${k}: ${JSON.stringify(v, null, 2).split('\n').join('\n          ')},`);
    }
    parts.push(`        },`);
  }

  parts.push(`      ),`);
  return parts.join('\n');
}

function renderChapter(ch) {
  const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const arr = (items) =>
    items && items.length
      ? `[\n${items.map((i) => `      ${q(i)},`).join('\n')}\n    ]`
      : '[]';

  const head = [
    `  // ${'='.repeat(10)} ${ch.comment}`,
    `  {`,
    `    id: ${q(ch.id)},`,
    `    chapterNumber: ${ch.chapterNumber},`,
    `    title: ${q(ch.title)},`,
    `    titleTelugu: ${q(ch.titleTelugu)},`,
    `    description:\n      ${q(ch.description)},`,
    `    descriptionTelugu:\n      ${q(ch.descriptionTelugu)},`,
    `    board: '${ch.board || 'CBSE'}',`,
    `    estimatedHours: ${ch.estimatedHours},`,
    `    iconName: ${q(ch.iconName)},`,
    `    unitNumber: ${ch.unitNumber},`,
    `    unitLabel: ${q(ch.unitLabel)},`,
    `    unitLabelTelugu: ${q(ch.unitLabelTelugu)},`,
    `    curriculumSource: ${q(ch.curriculumSource)},`,
    `    learningOutcomes: ${arr(ch.learningOutcomes)},`,
    `    learningOutcomesTelugu: ${arr(ch.learningOutcomesTelugu)},`,
    `    topics: [`,
  ];

  const body = ch.topics.map(renderTopic).join('\n');
  const tail = [`    ],`, `  },`];
  return [...head, body, ...tail].join('\n');
}

export function build(cbseChapters) {
  const out = HEADER + cbseChapters.map(renderChapter).join('\n') + FOOTER;
  assertCleanText(out, 'cbse-seed');
  fs.writeFileSync(OUT, out, 'utf8');
  const topics = cbseChapters.reduce((a, c) => a + c.topics.length, 0);
  console.log(`cbse-seed.ts written: ${cbseChapters.length} chapters, ${topics} topics`);
}

/**
 * Guard against corrupted characters (U+FFFD) sneaking into the syllabus text,
 * which would otherwise be written silently into the curriculum.
 */
export function assertCleanText(text, label) {
  const bad = [...text.matchAll(/�/g)];
  if (bad.length) {
    const idx = bad[0].index ?? 0;
    throw new Error(
      `${label}: found ${bad.length} replacement character(s). ` +
        `Context: ...${text.slice(Math.max(0, idx - 60), idx + 60)}...`
    );
  }
  // Guard against a stray character from another Indic script sneaking into the
  // Telugu strings. Telugu (U+0C00-U+0C7F) and the punctuation block are allowed.
  const foreign = [...text.matchAll(/[\u0900-\u0BFF\u0C80-\u0CFF\u0D00-\u0D7F]/g)];
  if (foreign.length) {
    const i = foreign[0].index ?? 0;
    const cp = foreign[0][0].codePointAt(0);
    throw new Error(
      `${label}: found ${foreign.length} non-Telugu Indic character(s), ` +
        `first is U+${cp.toString(16).toUpperCase()}. ` +
        `Context: ...${text.slice(Math.max(0, i - 60), i + 60)}...`
    );
  }
}

export { renderChapter, renderTopic };