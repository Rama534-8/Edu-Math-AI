/**
 * One-shot generator for src/lib/curriculum/ap-state-board-seed.ts
 *
 * AP State Board = SCERT Andhra Pradesh, Class IX Mathematics, split into
 * Semester 1 and Semester 2. Section titles below are transcribed from
 *   9_Maths_SEM-1_Textbook.pdf
 *   9_Maths_SEM-2_Textbook.pdf
 * Running `node scripts/build-all.mjs` regenerates the seed file.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { renderChapter, assertCleanText } from './build-cbse.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(__dirname, '..', 'src/lib/curriculum/ap-state-board-seed.ts');

const HEADER = `import { t, type ChapterSeed } from './builders';

// ==============================================================================
// AP STATE BOARD (SCERT ANDHRA PRADESH) - CLASS IX MATHEMATICS
// Sources:
//   9_Maths_SEM-1_Textbook.pdf  - Semester 1, Chapters 1-6
//   9_Maths_SEM-2_Textbook.pdf  - Semester 2, Chapters 7-12
//
// Section titles and numbering (1.1, 1.2, ...) are taken from the textbooks.
// GENERATED by build-ap.mjs - edit scripts/ap-data.mjs, then re-run.
// Chapter + topic IDs match the previous curriculum-data.ts.
// ==============================================================================

export const AP_STATE_BOARD_SEED: ChapterSeed[] = [
`;

const FOOTER = `];
`;

export function build(apChapters) {
  const body = apChapters
    .map((ch) => renderChapter({ ...ch, board: 'AP_STATE_BOARD' }))
    .join('\n');
  assertCleanText(HEADER + body + FOOTER, 'ap-state-board-seed');
  fs.writeFileSync(OUT, HEADER + body + FOOTER, 'utf8');
  const topics = apChapters.reduce((a, c) => a + c.topics.length, 0);
  console.log(`ap-state-board-seed.ts written: ${apChapters.length} chapters, ${topics} topics`);
}