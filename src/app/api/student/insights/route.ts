import { NextResponse } from 'next/server';
import { requireRoles } from '@/lib/authz';
import { getDb } from '@/lib/db';
import { CLASS_9_CHAPTERS } from '@/lib/curriculum-data';
import { buildLessonHref } from '@/lib/lesson-href';
import { computeBeforeAfterComparison } from '@/lib/deterministic-evaluator';
import type { AssessmentSnapshot, BoardType, Chapter, Topic } from '@/types';

/**
 * Learning Insights API — weakness analysis + personalised learning path.
 *
 * EVERY number returned here is derived from records the student already has:
 *   - assessment_snapshots (baseline / quizzes / retests, question-level)
 *   - mock_exam_answers of submitted mock exams (question-level)
 *   - assignment_submissions that a teacher has actually graded
 * Nothing is generated by AI and nothing is invented: topics with fewer than
 * 2 graded answers are never labelled strong/weak, and improvement is only
 * reported when a real baseline + comparable follow-up snapshot pair exists
 * (same honesty rule as Before & After). Recommendations are always chosen
 * from the student's OWN board curriculum (CBSE / AP State Board, Class 9).
 */

const STRONG_THRESHOLD = 70;
const MIN_ATTEMPTS_PER_TOPIC = 2;
const INSUFFICIENT_MESSAGE = 'Complete more quizzes to generate personalized insights.';

interface TopicAgg {
  chapterId: string;
  topicId: string;
  attempted: number;
  correct: number;
}

interface TopicStat {
  chapterId: string;
  chapterTitle: string;
  topicId: string;
  topicTitle: string;
  topicTitleTelugu: string | null;
  accuracy: number;
  attempted: number;
  correct: number;
  inSelectedCurriculum: boolean;
}

interface ChapterStat {
  chapterId: string;
  chapterTitle: string;
  chapterNumber: number;
  accuracy: number | null;
  attempted: number;
  status: 'MASTERED' | 'DEVELOPING' | 'NEEDS_PRACTICE' | 'NOT_STARTED';
}

function normalizeBoard(value: unknown): BoardType {
  return value === 'AP_STATE_BOARD' ? 'AP_STATE_BOARD' : 'CBSE';
}

export async function GET() {
  try {
    const auth = await requireRoles(['STUDENT']);
    if ('error' in auth) return auth.error;

    const userId = auth.actor.userId;
    const db = getDb();

    const profile = db
      .prepare('SELECT board FROM student_profiles WHERE uid = ?')
      .get(userId) as { board?: string | null } | undefined;
    const board = normalizeBoard(profile?.board);

    const boardChapters = CLASS_9_CHAPTERS.filter((c) => c.board === board);
    const chapterById = new Map(CLASS_9_CHAPTERS.map((c) => [c.id, c]));

    // ---------------------------------------------------------------------------
    // 1. Quiz / baseline / retest snapshots — question-level correctness
    // ---------------------------------------------------------------------------
    const snapshotRows = db
      .prepare(
        `SELECT snapshot_json AS snapshotJson, created_at AS createdAt, is_baseline AS isBaseline, type AS type
         FROM assessment_snapshots WHERE student_id = ? ORDER BY datetime(created_at) ASC`
      )
      .all(userId) as { snapshotJson: string; createdAt: string; isBaseline: number; type: string }[];

    const snapshots: AssessmentSnapshot[] = [];
    const topicAgg = new Map<string, TopicAgg>();
    let totalGraded = 0;
    let totalCorrect = 0;

    const addAnswer = (chapterId: string, topicId: string, isCorrect: boolean) => {
      const key = `${chapterId}::${topicId}`;
      const agg = topicAgg.get(key) ?? { chapterId, topicId, attempted: 0, correct: 0 };
      agg.attempted += 1;
      if (isCorrect) agg.correct += 1;
      topicAgg.set(key, agg);
      totalGraded += 1;
      if (isCorrect) totalCorrect += 1;
    };

    for (const row of snapshotRows) {
      let payload: AssessmentSnapshot;
      try {
        payload = JSON.parse(row.snapshotJson) as AssessmentSnapshot;
      } catch {
        continue;
      }
      snapshots.push(payload);
      if (!Array.isArray(payload.evaluatedQuestions)) continue;
      for (const q of payload.evaluatedQuestions) {
        if (!q || typeof q.chapterId !== 'string' || typeof q.topicId !== 'string') continue;
        // Unanswered items are not evidence of strength or weakness.
        const answer = typeof q.studentAnswer === 'string' ? q.studentAnswer.trim() : '';
        if (!answer || answer.toLowerCase() === 'unanswered') continue;
        addAnswer(q.chapterId, q.topicId, q.isCorrect === true);
      }
    }

    // ---------------------------------------------------------------------------
    // 2. Mock exam question-level answers (submitted attempts only)
    // ---------------------------------------------------------------------------
    const mockAnswerRows = db
      .prepare(
        `SELECT a.chapter_id AS chapterId, a.topic_id AS topicId,
                a.is_correct AS isCorrect, a.selected_answer AS selectedAnswer
         FROM mock_exam_answers a
         JOIN mock_exam_attempts t ON t.id = a.attempt_id
         WHERE a.student_id = ? AND t.status = 'SUBMITTED'`
      )
      .all(userId) as {
      chapterId: string | null;
      topicId: string | null;
      isCorrect: number;
      selectedAnswer: string | null;
    }[];

    for (const row of mockAnswerRows) {
      if (!row.chapterId || !row.topicId) continue;
      const answer = (row.selectedAnswer ?? '').trim();
      if (!answer) continue; // unanswered
      addAnswer(row.chapterId, row.topicId, row.isCorrect === 1);
    }
    // ---------------------------------------------------------------------------
    // 3. Assignment results (only teacher-graded submissions)
    // ---------------------------------------------------------------------------
    const assignmentRows = db
      .prepare(
        `SELECT s.marks AS marks, a.total_marks AS totalMarks
         FROM assignment_submissions s
         JOIN assignments a ON a.id = s.assignment_id
         WHERE s.student_id = ? AND s.marks IS NOT NULL`
      )
      .all(userId) as { marks: number; totalMarks: number | null }[];

    let assignmentAveragePercent: number | null = null;
    if (assignmentRows.length > 0) {
      const pcts = assignmentRows.map((r) => {
        const total = r.totalMarks && r.totalMarks > 0 ? r.totalMarks : 100;
        return Math.max(0, Math.min(100, (r.marks / total) * 100));
      });
      assignmentAveragePercent = Math.round(pcts.reduce((a, b) => a + b, 0) / pcts.length);
    }

    const mockExamsSubmitted = (
      db
        .prepare(
          "SELECT COUNT(*) AS n FROM mock_exam_attempts WHERE student_id = ? AND status = 'SUBMITTED'"
        )
        .get(userId) as { n: number }
    ).n;

    // ---------------------------------------------------------------------------
    // 4. Topic classification (only with enough real evidence)
    // ---------------------------------------------------------------------------
    const topicStats: TopicStat[] = [];
    for (const agg of topicAgg.values()) {
      const chapter = chapterById.get(agg.chapterId);
      const topic: Topic | undefined = chapter?.topics.find((t) => t.id === agg.topicId);
      if (agg.attempted <= 0) continue;
      topicStats.push({
        chapterId: agg.chapterId,
        chapterTitle: chapter?.title ?? agg.chapterId,
        topicId: agg.topicId,
        topicTitle: topic?.title ?? agg.topicId,
        topicTitleTelugu: topic?.titleTelugu ?? null,
        accuracy: Math.round((agg.correct / agg.attempted) * 100),
        attempted: agg.attempted,
        correct: agg.correct,
        inSelectedCurriculum: chapter?.board === board,
      });
    }

    const withEvidence = topicStats.filter((t) => t.attempted >= MIN_ATTEMPTS_PER_TOPIC);
    const strongTopics = withEvidence
      .filter((t) => t.accuracy >= STRONG_THRESHOLD)
      .sort((a, b) => b.accuracy - a.accuracy);
    const needsPracticeTopics = withEvidence
      .filter((t) => t.accuracy < STRONG_THRESHOLD)
      .sort((a, b) => a.accuracy - b.accuracy);

    // ---------------------------------------------------------------------------
    // 5. Chapter performance for the student's OWN board only
    // ---------------------------------------------------------------------------
    const chapterAgg = new Map<string, { attempted: number; correct: number }>();
    for (const t of topicStats) {
      const agg = chapterAgg.get(t.chapterId) ?? { attempted: 0, correct: 0 };
      agg.attempted += t.attempted;
      agg.correct += t.correct;
      chapterAgg.set(t.chapterId, agg);
    }

    const chapterPerformance: ChapterStat[] = boardChapters.map((c) => {
      const agg = chapterAgg.get(c.id);
      if (!agg || agg.attempted === 0) {
        return {
          chapterId: c.id,
          chapterTitle: c.title,
          chapterNumber: c.chapterNumber,
          accuracy: null,
          attempted: 0,
          status: 'NOT_STARTED' as const,
        };
      }
      const accuracy = Math.round((agg.correct / agg.attempted) * 100);
      const status: ChapterStat['status'] =
        accuracy >= STRONG_THRESHOLD
          ? 'MASTERED'
          : agg.attempted < MIN_ATTEMPTS_PER_TOPIC
            ? 'DEVELOPING'
            : 'NEEDS_PRACTICE';
      return {
        chapterId: c.id,
        chapterTitle: c.title,
        chapterNumber: c.chapterNumber,
        accuracy,
        attempted: agg.attempted,
        status,
      };
    });
    // ---------------------------------------------------------------------------
    // 6. Recommended next topic + personalised learning path
    // ---------------------------------------------------------------------------
    type Recommendation = {
      chapterId: string;
      chapterTitle: string;
      topicId: string;
      topicTitle: string;
      accuracy: number | null;
      reason: string;
      lessonHref: string;
      learningPath: { label: string; href: string }[];
    };

    let recommended: Recommendation | null = null;

    const buildRecommendation = (
      chapter: Chapter,
      topic: Topic | null,
      accuracy: number | null,
      reason: string
    ): Recommendation => {
      const lessonHref = topic
        ? buildLessonHref(chapter, Math.max(1, chapter.topics.findIndex((t) => t.id === topic.id) + 1))
        : buildLessonHref(chapter, 1);
      return {
        chapterId: chapter.id,
        chapterTitle: chapter.title,
        topicId: topic?.id ?? chapter.topics[0]?.id ?? chapter.id,
        topicTitle: topic?.title ?? chapter.topics[0]?.title ?? chapter.title,
        accuracy,
        reason,
        lessonHref,
        learningPath: [
          { label: 'Review the lesson', href: lessonHref },
          { label: 'Practice 5 questions', href: '/student/practice' },
          { label: 'Take Retest', href: '/student/quizzes' },
          { label: 'Check mastery', href: '/student/progress' },
        ],
      };
    };

    // Priority 1: weak topic that is inside the student's selected curriculum.
    const weakInCurriculum = needsPracticeTopics
      .filter((t) => t.inSelectedCurriculum)
      .map((t) => ({ stat: t, chapter: chapterById.get(t.chapterId) }))
      .filter((x): x is { stat: TopicStat; chapter: Chapter } => Boolean(x.chapter));
    if (weakInCurriculum.length > 0) {
      const { stat, chapter } = weakInCurriculum[0];
      const topic = chapter.topics.find((t) => t.id === stat.topicId) ?? null;
      recommended = buildRecommendation(
        chapter,
        topic,
        stat.accuracy,
        `Accuracy is ${stat.accuracy}% in this topic (${stat.correct}/${stat.attempted} correct).`
      );
    } else {
      // Priority 2: weak chapter-level evidence inside the curriculum.
      const weakChaptersInCurriculum = chapterPerformance
        .filter((c) => c.status === 'NEEDS_PRACTICE' || c.status === 'DEVELOPING')
        .sort((a, b) => (a.accuracy ?? 100) - (b.accuracy ?? 100));
      // Priority 3: a chapter of the selected board the student has not started.
      const notStarted = chapterPerformance.find((c) => c.status === 'NOT_STARTED');
      const target = weakChaptersInCurriculum[0] ?? notStarted;
      if (target) {
        const chapter = chapterById.get(target.chapterId);
        if (chapter) {
          recommended = buildRecommendation(
            chapter,
            null,
            target.accuracy,
            target.accuracy === null
              ? 'This chapter of your selected curriculum has not been attempted yet.'
              : `Chapter accuracy is ${target.accuracy}% (${target.status.replace('_', ' ').toLowerCase()}).`
          );
        }
      }
    }

    // ---------------------------------------------------------------------------
    // 7. Improvement — only from a real, comparable baseline/follow-up pair
    // ---------------------------------------------------------------------------
    const sortedDesc = [...snapshots].sort(
      (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()
    );
    const baseline = sortedDesc.find((s) => s.isBaseline || s.type === 'BASELINE') ?? null;
    const nonBaseline = sortedDesc.filter((s) => !(s.isBaseline || s.type === 'BASELINE'));
    const comparableCandidates = nonBaseline.filter(
      (s) =>
        s.type === 'RETEST' ||
        s.quizId === 'comparable-post-retest-class9' ||
        (baseline !== null && s.quizId === baseline.quizId)
    );
    const latestComparable = comparableCandidates[0] ?? nonBaseline[0] ?? null;
    const comparison = baseline ? computeBeforeAfterComparison(baseline, latestComparable) : null;
    const comparable = Boolean(comparison && comparison.comparableCriteriaMet);

    const hasEnoughData = totalGraded > 0;

    return NextResponse.json({
      board,
      hasEnoughData,
      message: hasEnoughData ? null : INSUFFICIENT_MESSAGE,
      totals: {
        gradedAnswers: totalGraded,
        quizzesTaken: snapshots.length,
        retestsTaken: snapshots.filter((s) => s.isRetest).length,
        mockExamsSubmitted,
        gradedAssignments: assignmentRows.length,
        assignmentAveragePercent,
        curriculumChapterCount: boardChapters.length,
      },
      overallAccuracy: totalGraded > 0 ? Math.round((totalCorrect / totalGraded) * 100) : null,
      strongTopics,
      needsPracticeTopics,
      recommended,
      improvement: {
        available: comparable,
        scoreChangePercentagePoints:
          comparable && comparison ? comparison.scoreChangePercentagePoints : null,
        baselinePercentage: comparable && comparison ? comparison.baselineSnapshot.percentage : null,
        latestPercentage: comparable && comparison ? comparison.latestSnapshot.percentage : null,
        reason: comparison?.comparisonReason ?? 'Complete your baseline diagnostic to measure improvement.',
      },
      chapterPerformance,
      generatedAt: new Date().toISOString(),
    });
  } catch (error) {
    console.error('[Student Insights API] Error:', error);
    return NextResponse.json({ error: 'Failed to build learning insights.' }, { status: 500 });
  }
}